-- Messenger App — Database Schema
-- Current schema as of V9 migration (all Flyway migrations V1–V9 merged).
-- Хранимых процедур и триггеров нет — вся бизнес-логика на уровне Java/Spring.

-- ──────────────────────────────────────────────
-- Users & sessions
-- ──────────────────────────────────────────────

create table app_users (
    id                    uuid primary key,
    username              varchar(24)  not null unique,
    email                 varchar(320) not null unique,
    display_name          varchar(40)  not null unique,
    profession            varchar(160),
    avatar_url            text,
    password_hash         varchar(255) not null,
    password_version      bigint       not null default 1,
    mail_enabled          boolean      not null default true,  -- V4
    created_at            timestamp with time zone not null,
    email_verified_at     timestamp with time zone
);

create table user_sessions (
    id           uuid primary key,
    user_id      uuid not null references app_users(id) on delete cascade,
    token_hash   varchar(64)  not null,
    device_name  varchar(160) not null,
    created_at   timestamp with time zone not null,
    last_used_at timestamp with time zone not null,
    expires_at   timestamp with time zone not null,
    revoked_at   timestamp with time zone
);

create index idx_user_sessions_user_id   on user_sessions (user_id);
create index idx_user_sessions_expires_at on user_sessions (expires_at);

-- ──────────────────────────────────────────────
-- Chats
-- ──────────────────────────────────────────────

create table chat_rooms (
    id                             uuid primary key,
    title                          varchar(255),
    is_direct                      boolean not null,
    avatar_url                     text,
    owner_user_id                  uuid references app_users(id) on delete set null,
    direct_user_low_id             uuid references app_users(id) on delete cascade,
    direct_user_high_id            uuid references app_users(id) on delete cascade,
    prejoin_history_policy         varchar(24) not null default 'FULL_HISTORY',
    membership_version             bigint      not null default 0,
    pinned_message_id              uuid,   -- legacy single-pin; superseded by chat_pinned_messages
    pinned_at                      timestamp with time zone,
    created_at                     timestamp with time zone not null,
    constraint chk_chat_rooms_prejoin_history_policy
        check (prejoin_history_policy in ('JOIN_ONLY', 'FULL_HISTORY')),
    constraint chk_chat_rooms_direct_pair
        check (
            (direct_user_low_id is null and direct_user_high_id is null)
            or (
                is_direct = true
                and direct_user_low_id  is not null
                and direct_user_high_id is not null
                and direct_user_low_id <> direct_user_high_id
            )
        ),
    constraint uk_chat_rooms_direct_pair unique (direct_user_low_id, direct_user_high_id)
);

create table chat_participants (
    id                              uuid primary key,
    chat_id                         uuid not null references chat_rooms(id) on delete cascade,
    user_id                         uuid not null references app_users(id) on delete cascade,
    joined_at                       timestamp with time zone not null,
    left_at                         timestamp with time zone,  -- V6
    prejoin_history_access_granted_at timestamp with time zone,
    constraint uk_chat_participants_chat_user unique (chat_id, user_id)
);

create index idx_chat_participants_user_id        on chat_participants (user_id);
create index idx_chat_participants_chat_id_left_at on chat_participants (chat_id, left_at, joined_at);  -- V6

-- ──────────────────────────────────────────────
-- Messages
-- ──────────────────────────────────────────────

create table chat_messages (
    id                        uuid primary key,
    chat_id                   uuid not null references chat_rooms(id) on delete cascade,
    sender_id                 uuid not null references app_users(id) on delete cascade,
    content_ciphertext        bytea       not null,
    content_iv                bytea       not null,
    content_key_version       integer     not null,
    content_algorithm         varchar(32) not null,
    client_message_id         varchar(120),
    server_order              bigint generated by default as identity not null,
    reply_to_message_id       uuid references chat_messages(id) on delete set null,
    forwarded_at              timestamp with time zone,                                          -- V7
    forwarded_from_sender_id  uuid references app_users(id) on delete set null,                 -- V7
    edited_at                 timestamp with time zone,
    created_at                timestamp with time zone not null,
    constraint uk_chat_messages_sender_client_message unique (chat_id, sender_id, client_message_id),
    constraint uk_chat_messages_server_order           unique (server_order)
);

alter table chat_rooms
    add constraint fk_chat_rooms_pinned_message
        foreign key (pinned_message_id)
        references chat_messages(id)
        on delete set null;

create index idx_chat_messages_chat_id_created_at_id    on chat_messages (chat_id, created_at, id);
create index idx_chat_messages_chat_id_server_order     on chat_messages (chat_id, server_order);
create index idx_chat_messages_forwarded_from_sender_id on chat_messages (forwarded_from_sender_id);  -- V7

create table chat_message_keys (
    id             uuid primary key,
    chat_id        uuid    not null references chat_rooms(id) on delete cascade,
    key_version    integer not null,
