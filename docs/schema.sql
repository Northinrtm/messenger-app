    key_reference  varchar(255) not null,
    created_at     timestamp with time zone not null,
    constraint uk_chat_message_keys_chat_version unique (chat_id, key_version)
);

create index idx_chat_message_keys_chat_id_version on chat_message_keys (chat_id, key_version desc);

create table chat_message_links (  -- V3
    id             uuid primary key,
    chat_id        uuid    not null references chat_rooms(id) on delete cascade,
    message_id     uuid    not null references chat_messages(id) on delete cascade,
